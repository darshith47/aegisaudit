from datetime import datetime
from sqlalchemy.orm import Session
from app.models.assessment import Assessment
from app.models.finding import Finding


class ExecutiveReportGenerator:
    """Generates professional executive cybersecurity audit reports."""

    @staticmethod
    def generate_markdown_report(db: Session, assessment_id: int) -> str:
        assessment = db.query(Assessment).filter(Assessment.id == assessment_id).first()
        if not assessment:
            raise ValueError(f"Assessment #{assessment_id} not found.")

        findings = db.query(Finding).filter(Finding.assessment_id == assessment_id).all()

        report_lines = [
            "# AegisAudit — Security Assessment Executive Report",
            "",
            "> **IMPORTANT NOTICE**: Authorized Security Testing Only. Confidential report.",
            "",
            "## 1. Assessment Overview",
            "",
            f"- **Assessment ID**: #{assessment.id}",
            f"- **Title**: {assessment.title}",
            f"- **Target**: `{assessment.target}`",
            f"- **Security Engine**: {assessment.engine.upper()}",
            f"- **Status**: {assessment.status.value.upper()}",
            f"- **Authorized Scope ID**: #{assessment.scope_id} ({assessment.scope.name})",
            f"- **Date Generated**: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}",
            "",
            "## 2. Executive Summary",
            "",
            f"An authorized credential security assessment was conducted against `{assessment.target}` using the `{assessment.engine}` engine under scope policy `{assessment.scope.name}`.",
            "",
            f"A total of **{len(findings)} security finding(s)** were identified during this assessment.",
            "",
            "## 3. Identified Security Findings",
            ""
        ]

        if not findings:
            report_lines.append("*No security vulnerabilities or weak credentials identified.*")
        else:
            for idx, f in enumerate(findings, start=1):
                mock_badge = " [DEMO / MOCK]" if f.is_mock else ""
                report_lines.extend([
                    f"### 3.{idx}. {f.title}{mock_badge}",
                    "",
                    f"- **Severity**: `{f.severity.value}`",
                    f"- **Vulnerability Type**: {f.vulnerability_type}",
                    f"- **Affected Target**: `{f.target}`",
                    "",
                    "#### Finding Details:",
                    f"{f.details}",
                    "",
                    "#### Recommended Remediation:",
                    f"{f.remediation or 'N/A'}",
                    "",
                    "---",
                    ""
                ])

        report_lines.extend([
            "## 4. Authorization & Compliance Attestation",
            "",
            f"This assessment was performed strictly in compliance with Scope Policy #{assessment.scope.id} (`{assessment.scope.allowed_targets}`). Target scope authorization was verified prior to execution.",
            "",
            "_Report auto-generated by AegisAudit Credential Assessment Platform v0.1.0._"
        ])

        return "\n".join(report_lines)

    @staticmethod
    def generate_html_report(db: Session, assessment_id: int) -> str:
        md_content = ExecutiveReportGenerator.generate_markdown_report(db, assessment_id)
        # Convert to structured dark-themed HTML report
        html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>AegisAudit Report - Assessment #{assessment_id}</title>
    <style>
        body {{ font-family: 'Segoe UI', system-ui, sans-serif; background: #0f172a; color: #f8fafc; padding: 40px; line-height: 1.6; }}
        .container {{ max-width: 900px; margin: 0 auto; background: #1e293b; padding: 32px; border-radius: 12px; box-shadow: 0 10px 30px rgba(0,0,0,0.5); }}
        h1 {{ color: #38bdf8; border-bottom: 2px solid #334155; padding-bottom: 12px; }}
        h2 {{ color: #818cf8; margin-top: 28px; }}
        h3 {{ color: #f43f5e; }}
        pre {{ background: #0f172a; padding: 16px; border-radius: 8px; border: 1px solid #334155; white-space: pre-wrap; }}
        .badge {{ background: #ef4444; color: white; padding: 4px 8px; border-radius: 4px; font-weight: bold; font-size: 0.85em; }}
        .notice {{ background: #0284c7; color: white; padding: 12px; border-radius: 6px; font-weight: 500; margin-bottom: 20px; }}
    </style>
</head>
<body>
    <div class="container">
        <pre>{md_content}</pre>
    </div>
</body>
</html>"""
        return html_content
